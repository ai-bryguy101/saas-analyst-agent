def table(rows, header=True):
    out = ['<div class="table-wrap"><table class="confluenceTable"><tbody>']
    for i, row in enumerate(rows):
        tag = "th" if header and i == 0 else "td"
        out.append("<tr>" + "".join(f'<{tag} class="confluence{tag.title()}">{c}</{tag}>' for c in row) + "</tr>")
    out.append("</tbody></table></div>")
    return "\n".join(out)


